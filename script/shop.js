function displayProducts(products, containerId) {
    const container = document.getElementById(containerId);

    products.forEach(product => {
        const card = document.createElement('div');
        card.className = 'swiper mySwiper';

        // собираем все фото в массив
        const photos = [product.photo, product.photo2, product.photo3].filter(p => p && p.trim() !== "");

        // формируем слайды динамически
        let slidesHTML = photos.map(p => `
            <div class="swiper-slide"><img src="${p}" alt="" class="product-img"></div>
        `).join("");

        // Пагинация только если есть больше одного слайда
        card.innerHTML = `
            <div class="swiper-wrapper">
                ${slidesHTML}
            </div>
            <div class="pagination-container">
            ${photos.length > 1 ? '<div class="swiper-pagination"></div>' : ""}
            </div>
            <p class="name">${product.name}</p>
            <span class="price">от ${product.price} руб.</span>
            <details class="description"> 
            <summary class="price">Состав:<br></summary>
            ${product.description}<br><br><a href="https://t.me/Ilonapodterebkova" target="_blank" class="btn buy-link">Заказать</a></details>
        `;

        container.appendChild(card);

        // инициализация Swiper только если есть несколько фото
        if (photos.length > 1) {
            new Swiper(card, {
                loop: true,
                slidesPerView: 1,
                spaceBetween: 30,
                pagination: {
                    el: card.querySelector('.swiper-pagination'),
                    clickable: true
                },
                autoplay: {
                    delay: 5000
                },
                keyboard: {
                    enabled: true,
                    onlyInViewport: false
                },
                simulateTouch: true,
                grabCursor: true
            });
        }
    });
}

